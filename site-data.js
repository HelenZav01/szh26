function initialsPhoto(name) {
  const [first = "?", , last = ""] = (name || "").trim().split(/\s+/);
  const initials = `${first[0] || "?"}${last[0] || ""}`;
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 300 400">
    <defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1">
      <stop offset="0" stop-color="#f6c445"/><stop offset="1" stop-color="#d2600f"/>
    </linearGradient></defs>
    <rect width="300" height="400" fill="url(#g)"/>
    <text x="150" y="215" text-anchor="middle" font-family="Montserrat, sans-serif"
      font-size="110" font-weight="800" fill="#fff" fill-opacity="0.9">${initials}</text>
  </svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

