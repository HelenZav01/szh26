const FILE_TYPES = {
  "application/pdf": "pdf",
  "application/msword": "doc",
  "application/vnd.openxmlformats-officedocument.wordprocessingml.document": "docx",
  "application/vnd.ms-powerpoint": "ppt",
  "application/vnd.openxmlformats-officedocument.presentationml.presentation": "pptx",
  "application/vnd.ms-excel": "xls",
  "application/vnd.openxmlformats-officedocument.spreadsheetml.sheet": "xlsx",
};
function fileType(src) {
  return src.startsWith("data:") ? FILE_TYPES[src.slice(5, src.indexOf(";"))] || "" : (src.match(/\.(\w+)(?:[?#]|$)/)?.[1] || "").toLowerCase();
}
const blobUrls = new Map();
function fileUrl(src) {
  if (!src.startsWith("data:")) return safeUrl(src);
  if (!fileType(src) || !src.includes(";base64,")) return "";
  if (!blobUrls.has(src)) {
    const [head, data] = src.split(",");
    const bytes = Uint8Array.from(atob(data), (c) => c.charCodeAt(0));
    blobUrls.set(src, URL.createObjectURL(new Blob([bytes], { type: head.slice(5).split(";")[0] })));
  }
  return blobUrls.get(src);
}

