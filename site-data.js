const dateFormat = new Intl.DateTimeFormat("uk-UA", { day: "numeric", month: "long", year: "numeric" });

function formatDate(iso) {
  return dateFormat.format(new Date(`${iso}T12:00:00`));
}

function plural(n, one, few, many) {
  const n10 = n % 10, n100 = n % 100;
  if (n10 === 1 && n100 !== 11) return one;
  if (n10 >= 2 && n10 <= 4 && (n100 < 12 || n100 > 14)) return few;
  return many;
}

function setPhoto(img, src, size) {
  const copy = size && src.startsWith("assets/") ? `assets/${size}/${src.slice(7)}` : src;
  if (copy !== src) img.addEventListener("error", () => (img.src = src), { once: true });
  img.decoding = "async";
  img.src = copy;
}

