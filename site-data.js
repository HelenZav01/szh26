const SAFE_PROTOCOLS = ["http:", "https:", "mailto:", "tel:", "file:"];
function safeUrl(url, fallback = "") {
  const value = String(url || "").trim();
  if (!value) return fallback;
  try {
    return SAFE_PROTOCOLS.includes(new URL(value, location.href).protocol) ? value : fallback;
  } catch {
    return fallback;
  }
}

function autoSeason(date = new Date()) {
  const m = date.getMonth();
  if (m >= 8 && m <= 10) return "halloween";
  if (m === 11 || m <= 1) return "winter";
  return "normal";
}

