function slugify(text) {
  return [...String(text || "").toLowerCase()].map((c) => TRANSLIT[c] ?? c).join("")
    .replace(/[^a-z0-9]+/g, "-").replace(/^-+|-+$/g, "");
}

function teacherSlug(t) {
  return t.id || t.photo?.match(/teachers\/([\w-]+)\.\w+$/)?.[1] || slugify(t.short || t.name) || "teacher";
}

